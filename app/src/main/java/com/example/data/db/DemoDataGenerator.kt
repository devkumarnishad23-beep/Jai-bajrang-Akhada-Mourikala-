    fun getSampleAttendance(): List<AttendanceRecord> {
        val list = mutableListOf<AttendanceRecord>()
        val dates = listOf("2026-08-22", "2026-08-21", "2026-08-20", "2026-08-19", "2026-08-18", "2026-08-17", "2026-08-16")
        
        for (i in 1..10) {
            val sId = "JBA-2026-%03d".format(i)
            dates.forEachIndexed { index, d ->
                val status = when {
                    index == 0 -> if (i == 3) "Late" else if (i == 7) "Leave" else "Present"
                    index == 2 && i == 6 -> "Absent"
                    index == 4 && i == 9 -> "Leave"
                    else -> "Present"
                }
                list.add(AttendanceRecord(studentId = sId, date = d, status = status, remarks = if (status != "Present") "कारण: सूचित किया गया" else ""))
            }
        }
        return list
    }

